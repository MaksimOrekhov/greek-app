import { trainerTopics } from './topics.ts'
import type { TrainerExerciseType } from './types.ts'

export interface MultiSelectOption {
  id: string
  text: string
  correct: boolean
}

export interface MultiSelectQuestion {
  id: string
  topicId: string
  type: Extract<TrainerExerciseType, 'multi-select'>
  prompt: string
  options: MultiSelectOption[]
  explanation: string
}

type Choice = [text: string, correct: boolean]

function question(
  id: string,
  topicId: string,
  prompt: string,
  choices: Choice[],
  explanation: string,
): MultiSelectQuestion {
  return {
    id,
    topicId,
    type: 'multi-select',
    prompt,
    options: choices.map(([text, correct], index) => ({ id: `${id}-option-${index + 1}`, text, correct })),
    explanation,
  }
}

