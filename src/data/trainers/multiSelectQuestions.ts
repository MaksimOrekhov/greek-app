export function validateMultiSelectQuestionBank(
  questions: MultiSelectQuestion[] = trainerMultiSelectQuestions,
  topics = trainerTopics,
): string[] {
  const errors: string[] = []
  const questionIds = new Set<string>()
  const topicIds = new Set(topics.map((topic) => topic.id))

  for (const item of questions) {
    if (questionIds.has(item.id)) errors.push(`Повторяется вопрос тренажёра: ${item.id}`)
    questionIds.add(item.id)
    if (!item.id || !item.topicId || !item.prompt.trim() || !item.explanation.trim()) {
      errors.push(`Неполные данные вопроса тренажёра: ${item.id}`)
    }
    if (!topicIds.has(item.topicId)) errors.push(`Для вопроса ${item.id} не найдена тема ${item.topicId}`)
    if (item.type !== 'multi-select') errors.push(`Неверный тип вопроса: ${item.id}`)
    if (item.options.length < 4) errors.push(`В вопросе ${item.id} меньше четырёх вариантов`)

    const optionIds = new Set<string>()
    const optionTexts = new Set<string>()
    let correctCount = 0
    for (const option of item.options) {
      if (optionIds.has(option.id)) errors.push(`Повторяется вариант ${option.id} в вопросе ${item.id}`)
      optionIds.add(option.id)
      const normalizedText = option.text.trim().normalize('NFC').toLocaleLowerCase('ru')
      if (optionTexts.has(normalizedText)) errors.push(`Повторяется текст варианта в вопросе ${item.id}`)
      optionTexts.add(normalizedText)
      if (!option.id || !option.text.trim()) errors.push(`Пустой вариант ответа в вопросе ${item.id}`)
      if (option.correct) correctCount += 1
    }
    if (correctCount < 2) errors.push(`В вопросе ${item.id} должно быть не меньше двух правильных вариантов`)
    if (correctCount >= item.options.length) errors.push(`В вопросе ${item.id} должен быть хотя бы один неправильный вариант`)
  }

  return errors
}
